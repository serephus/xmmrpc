//! Byte-exact wire vectors ported from the reference implementation.
//!
//! Generated from the reverse-engineered `xmmrpc` protocol tables so that
//! the Rust encoder provably matches the original byte for byte.

use xmmrpc::requests;

fn unhex(hex: &str) -> Vec<u8> {
    assert!(hex.len().is_multiple_of(2));
    (0..hex.len())
        .step_by(2)
        .map(|i| u8::from_str_radix(&hex[i..i + 2], 16).unwrap())
        .collect()
}

