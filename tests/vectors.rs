#[test]
fn connect_to_datachannel() {
    let expected =
        unhex("55180204000000180204000000002f73696f7363632f504349452f494f534d2f4950532f3000");
    assert_eq!(
        requests::connect_to_datachannel("/sioscc/PCIE/IOSM/IPS/0").unwrap(),
        expected
    );
}

