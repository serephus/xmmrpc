//! Firmware RPC call identifiers.
//!
//! Ported from the reverse-engineered `xmm7360-pci` protocol tables.

/// A firmware RPC command identifier.
#[derive(Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Debug, Hash)]
pub struct CallId(pub u32);

impl CallId {
    /// Construct a call id from its raw wire value.
    pub const fn new(raw: u32) -> Self {
        Self(raw)
    }

    /// The raw wire value.
    pub const fn raw(self) -> u32 {
        self.0
    }
}

impl core::fmt::Display for CallId {
    fn fmt(&self, f: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {
        match call_name(self.0) {
            Some(name) => f.write_str(name),
            None => write!(f, "0x{:x}", self.0),
        }
    }
}

