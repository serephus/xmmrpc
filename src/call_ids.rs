/// Look up a call id by its firmware name.
pub fn call_id(name: &str) -> Option<CallId> {
    CALL_IDS
        .iter()
        .find_map(|(n, id)| (*n == name).then_some(CallId(*id)))
}

/// Look up the firmware name of a call id.
pub fn call_name(raw: u32) -> Option<&'static str> {
    CALL_IDS
        .iter()
        .find_map(|(n, id)| (*id == raw).then_some(*n))
}
